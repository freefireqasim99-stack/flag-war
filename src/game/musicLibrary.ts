export const DEFAULT_TRACK_ID = 'tiktok-viral-beat-drop';

export function getTrackById(id: string | 'none'): MusicTrackDef | null {
  if (!id || id === 'none') return null;
  return MUSIC_TRACKS.find((t) => t.id === id) ?? MUSIC_TRACKS[0];
}

export function getTracksByCategory(categoryId: MusicCategoryId): MusicTrackDef[] {
  return MUSIC_TRACKS.filter((t) => t.categoryId === categoryId);
}

export function pickRandomTrendingTrack(excludeId?: string): MusicTrackDef {
  // Prioritize high-energy trending tracks (TikTok, YouTube, Sports, plus upbeat Reels/Gaming)
  const pool = MUSIC_TRACKS.filter((t) => t.id !== excludeId);
  const chosen = pool[Math.floor(Math.random() * pool.length)] ?? MUSIC_TRACKS[0];
  return chosen;
}
